const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const key = 'cromapdv_snapshot_v1';
(async () => {
  const browser = await chromium.launch({channel:'msedge'});
  try {
    const context = await browser.newContext();
    const page = await context.newPage();
    const url = process.env.PDV_TEST_URL || 'http://127.0.0.1:4173/';
    const load = async p => { await p.goto(url); await p.getByText(/Modo demonstração fiscal/).waitFor(); };
    const read = p => p.evaluate(k => JSON.parse(localStorage.getItem(k)), key);
    const checkout = async p => { await p.getByRole('button',{name:/FINALIZAR VENDA \(F2\)/}).click(); await p.getByRole('button',{name:/CONFIRMAR VENDA/}).waitFor(); };
    const confirm = p => p.getByRole('button',{name:/CONFIRMAR VENDA/});
    await load(page);
    await page.getByLabel("Nome comercial").fill("Loja de teste");
    await page.getByLabel(/Usar dados de demonstração/).check();
    await page.getByRole("button",{name:"Começar"}).click();
    await page.getByRole("heading",{name:"Configure seu negócio"}).waitFor({state:"hidden"});
    await checkout(page);
    const cash = page.locator('form input').first();
    await cash.fill('0');
    assert(await confirm(page).isDisabled(), 'dinheiro insuficiente deve bloquear');
    console.log('PASS pagamento em dinheiro insuficiente');
    await page.keyboard.press('Escape');
    await checkout(page);
    await confirm(page).click();
    await confirm(page).waitFor({state:'hidden'});
    let state = await read(page);
    assert.equal(state.cart.length,0);
    assert.equal(state.movements[0].description,'Venda sem NFC-e');
    assert.equal(state.movements[0].invoiceNumero,undefined);
    assert.equal(state.invoices.length,2);
    await page.reload();
    assert.deepEqual(await read(page),state);
    console.log('PASS venda sem NFC-e e persistência após recarregar');

    await page.evaluate(k => {
      const snapshot = JSON.parse(localStorage.getItem(k));
      const product = snapshot.products.find(p => p.stock > 0);
      product.stock = 1;
      snapshot.cart = [{product, quantity: 2}];
      localStorage.setItem(k,JSON.stringify(snapshot));
    },key);
    await page.reload();
    await checkout(page);
    await confirm(page).click();
    await page.getByText(/Estoque insuficiente/).waitFor();
    assert.equal((await read(page)).cart[0].quantity,2);
    console.log('PASS bloqueio de estoque insuficiente ao finalizar');

    await page.evaluate(k => {
      const snapshot = JSON.parse(localStorage.getItem(k));
      snapshot.cart[0].quantity = 1;
      localStorage.setItem(k,JSON.stringify(snapshot));
    },key);
    await page.reload();
    const stale = await context.newPage();
    await load(stale);
    state = await read(page);
    const productId = state.cart[0].product.id;
    await checkout(page);
    await page.getByRole('checkbox',{name:/NFC-e simulada/}).check();
    await confirm(page).click();
    await page.getByText('SIMULAÇÃO · SEM VALOR FISCAL').waitFor();
    const sold = await read(page);
    assert.equal(sold.products.find(p=>p.id===productId).stock,0);
    assert.equal(sold.storeConfig.proximoNumeroNfce,state.storeConfig.proximoNumeroNfce+1);
    await checkout(stale);
    await confirm(stale).click();
    await stale.getByText(/Dados atualizados em outra aba/).waitFor();
    assert.deepEqual(await read(page),sold);
    console.log('PASS venda simulada e proteção contra venda em aba desatualizada');

    await page.getByRole('button',{name:/Simular cancelamento/}).click();
    const reason = page.getByRole('button',{name:/Confirmar Estorno/i});
    await reason.click();
    await page.waitForFunction(k=>JSON.parse(localStorage.getItem(k)).movements[0].type==='ESTORNO',key);
    const canceled = await read(page);
    assert.equal(canceled.products.find(p=>p.id===productId).stock,1);
    assert.equal(canceled.invoices[0].status,'CANCELADA');
    console.log('PASS cancelamento, estorno e reposição');

    await page.reload();
    const search = page.getByPlaceholder(/Buscar produto ou bipar/);
    const returned = canceled.products.find(p => p.id === productId);
    await search.fill('2*' + returned.barcode);
    await search.press('Enter');
    await page.getByText('Estoque insuficiente.').waitFor();
    assert.deepEqual(await read(page), canceled);
    await search.fill(returned.barcode);
    await search.press('Enter');
    await page.waitForFunction(k => JSON.parse(localStorage.getItem(k)).cart.length === 1, key);
    console.log('PASS código de barras e bloqueio de quantidade na busca');

    const beforeFailure = await read(page);
    await checkout(page);
    await page.evaluate(k => {
      const original = Storage.prototype.setItem;
      Storage.prototype.setItem = function (name, value) {
        if (name === k) throw new DOMException('Armazenamento cheio', 'QuotaExceededError');
        return original.call(this, name, value);
      };
    }, key);
    await confirm(page).click();
    await page.getByText(/Não foi possível salvar os dados/).waitFor();
    assert(await confirm(page).isVisible());
    assert.deepEqual(await read(page), beforeFailure);
    console.log('PASS falha de gravação preserva carrinho, caixa e estoque');

    const fresh = await browser.newPage();
    await load(fresh);
    await fresh.getByLabel('Nome comercial').fill('Salão de teste');
    await fresh.getByLabel('Logotipo (opcional)').setInputFiles('public/pwa-192x192.png');
    await fresh.getByAltText('Prévia do logotipo').waitFor();
    await fresh.getByRole('radio', { name: /Operação mista/ }).check();
    await fresh.getByRole('button', { name: 'Começar' }).click();
    await fresh.getByRole('heading', { name: 'Configure seu negócio' }).waitFor({ state: 'hidden' });
    const initial = await read(fresh);
    assert.equal(initial.business.profile, 'mixed');
    assert.match(initial.business.logo, /^data:image\/png;base64,/);
    assert.equal(initial.registerOpen, false);
    assert.deepEqual(initial.products, []);
    assert.deepEqual(initial.movements, []);
    await fresh.getByRole('button', { name: 'Configuração fiscal', exact: true }).click();
    await fresh.getByRole('button', { name: /Configuração de serviços/ }).click();
    await fresh.getByLabel('Município do prestador').fill('São Paulo');
    await fresh.getByLabel('Código IBGE do município').fill('3550308');
    await fresh.getByLabel('Inscrição municipal').fill('Cadastro de teste');
    await fresh.getByLabel('Emissor de serviços').selectOption('municipal');
    await fresh.getByRole('button', { name: 'Salvar cadastro de serviços' }).click();
    await fresh.getByText('Cadastro de serviços salvo.').waitFor();
    await fresh.reload();
    await fresh.getByRole('button', { name: 'Configuração fiscal', exact: true }).click();
    await fresh.getByRole('button', { name: /Configuração de serviços/ }).click();
    assert.equal(await fresh.getByLabel('Código IBGE do município').inputValue(), '3550308');
    assert.equal(await fresh.getByLabel('Emissor de serviços').inputValue(), 'municipal');
    assert.deepEqual((await read(fresh)).storeConfig, initial.storeConfig);
    await fresh.getByRole('button', { name: 'Catálogo', exact: true }).click();
    await fresh.getByRole('button', { name: 'Cadastrar item' }).click();
    await fresh.getByPlaceholder('Nome do item').fill('Shampoo teste');
    await fresh.getByLabel('Preço unitário').fill('20');
    await fresh.getByLabel('Estoque atual').fill('2');
    await fresh.getByRole('button', { name: 'Salvar item' }).click();
    await fresh.waitForFunction(k => JSON.parse(localStorage.getItem(k)).products.length === 1, key);
    await fresh.getByRole('button', { name: 'Cadastrar item' }).click();
    await fresh.getByLabel('Tipo do item').selectOption('service');
    await fresh.getByPlaceholder('Nome do item').fill('Corte teste');
    await fresh.getByLabel('Preço unitário').fill('40');
    assert.equal(await fresh.getByLabel('Estoque atual').count(), 0);
    await fresh.getByRole('button', { name: 'Salvar item' }).click();
    await fresh.waitForFunction(k => JSON.parse(localStorage.getItem(k)).products.length === 2, key);
    await fresh.reload();
    await fresh.getByText('Caixa Fechado', { exact: true }).waitFor();
    await fresh.getByRole('button', { name: /F7: Sangria/ }).click();
    await fresh.getByRole('button', { name: 'Reabrir Caixa' }).click();
    await fresh.waitForFunction(k => JSON.parse(localStorage.getItem(k)).registerOpen, key);
    await fresh.keyboard.press('Escape');
    const find = fresh.getByPlaceholder(/Buscar produto ou bipar/);
    await find.fill('Shampoo teste');
    await find.press('Enter');
    await fresh.waitForFunction(k => JSON.parse(localStorage.getItem(k)).cart.length === 1, key);
    await find.fill('Corte teste');
    await find.press('Enter');
    await fresh.waitForFunction(k => JSON.parse(localStorage.getItem(k)).cart.length === 2, key);
    await checkout(fresh);
    await fresh.getByLabel('Tipo de atendimento').selectOption('repair');
    assert(await fresh.getByRole('checkbox', { name: /Conserto sem simulação/ }).isDisabled());
    await confirm(fresh).click();
    await confirm(fresh).waitFor({ state: 'hidden' });
    const mixed = await read(fresh);
    assert.equal(mixed.movements[0].amount, 60);
    assert.equal(mixed.movements[0].operation, 'repair');
    assert.equal(mixed.movements[0].items.length, 2);
    assert.equal(mixed.products.find(p => p.name === 'Shampoo teste').stock, 1);
    assert.equal(mixed.products.find(p => p.kind === 'service').stock, 0);
    assert.deepEqual(mixed.invoices, []);
    await fresh.getByRole('button', { name: 'Vendas', exact: true }).click();
    await fresh.getByRole('heading', { name: 'Histórico de vendas' }).waitFor();
    await fresh.getByRole('button', { name: /DINHEIRO/ }).click();
    await fresh.getByText('1 × Corte teste').waitFor();
    await fresh.getByText('1 × Shampoo teste').waitFor();
    await fresh.getByText('Conserto ou assistência técnica', { exact: true }).waitFor();
    console.log('PASS cadastro fiscal separado e conserto misto sem emissão');
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1});
